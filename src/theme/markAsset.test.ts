import fs from 'node:fs';
import path from 'node:path';

import sharp from 'sharp';

import { makeStyles } from './styles';

// **The one graphic Ponor's screens draw, checked as a graphic** (DESIGN.md §0.1/§0.3, M1h).
// The tab bar's glyphs are checked at the end of this file.
//
// It lives beside the theme because what it pins is a claim about COLOUR, and colour is this
// directory's subject: `assets/images/mark-mono.png` is the mark `EmptyState` draws at 120 pt,
// and the whole reason it exists as a separate asset from `icon.png` is that the on-screen mark
// may not carry the depth gradient. §0.3 strokes that gradient on the icon, where the mark is
// the only thing there is; inside the interface the same gradient is colour used as **brand**,
// and §0.1 says colour encodes depth and nothing else — on the one screen whose entire job is
// teaching that rule.
//
// **Why the artifact and not the script.** `scripts/build-icons.mjs` already refuses to build a
// mono mark that carries a second colour, and that guard is the fix; this is the proof it ran.
// The PNG is committed (Metro bundles it, so it has to be), `icons:build` is not part of any
// gate, and a mark regenerated by hand — or edited, or copied from `icon.png` because it looked
// close enough — would reach a diver with nothing in between. What is asserted is therefore the
// property, not the pipeline: **every pixel a diver can see is one colour.**
//
// A `tintColor` repaints exactly those pixels from the theme's ink (`emptyStateMark`,
// styles.ts), so the shipped white is what the tint replaces rather than what anybody sees.
// That is also why this test is worth more than it looks: a tint uses only the alpha channel on
// every platform we can check, so a gradient asset would render identically everywhere we would
// think to look and show its true colours only where tinting quietly does not apply.
const MARK = path.join(__dirname, '..', '..', 'assets', 'images', 'mark-mono.png');

describe('the mark the first-run screen draws', () => {
  it('carries exactly one colour, over a transparent ground', async () => {
    const { data, info } = await sharp(MARK).raw().toBuffer({ resolveWithObject: true });
    expect(info.channels).toBe(4);

    const inks = new Set<string>();
    let visible = 0;
    for (let i = 0; i < data.length; i += info.channels) {
      // Alpha 0 is the ground, and it is the whole of the image outside the drawing: an opaque
      // background would put a rectangle of ink behind the mark on both themes, one of which
      // would be invisible. Anti-aliased edges are partially transparent and still have to
      // agree on the colour, so they are counted rather than skipped.
      if (data[i + 3] === 0) continue;
      visible += 1;
      inks.add([data[i], data[i + 1], data[i + 2]].join(','));
    }

    // The drawing is actually there — an empty or fully transparent PNG would satisfy "one
    // colour" vacuously, and would render as a 120 pt hole above the label.
    expect(visible).toBeGreaterThan(1000);
    expect([...inks]).toEqual(['255,255,255']);
  });

  // **The wave stays behind the profile, and in a monochrome mark that has to be alpha.**
  // §0.3 puts it there on purpose ("chosen to sit quietly behind the profile") and uses
  // COLOUR to do it — a flat grey wave against a saturated gradient descent. Flatten both to
  // one ink at one width and they stop being two objects: the wave's ends curve down into the
  // profile's start, and the 120 pt render reads as a longhorn skull. Seen on the simulator,
  // which is the only place it could be seen.
  //
  // Pinned as two large populations rather than as an exact alpha, because the number is a
  // design judgement and the rule is the hierarchy. Anti-aliasing alone cannot satisfy it: an
  // opaque wave leaves only stroke edges near half alpha, a few hundred pixels at this size,
  // where a translucent one contributes the whole interior of a stroke running the full width
  // of the mark.
  it('keeps the wave translucent behind a solid profile, so the two read as two objects', async () => {
    const { data, info } = await sharp(MARK).raw().toBuffer({ resolveWithObject: true });
    let solid = 0;
    let translucent = 0;
    for (let i = 0; i < data.length; i += info.channels) {
      const alpha = data[i + 3];
      if (alpha === 255) solid += 1;
      // A band, not a value: the SVG rasteriser does not hand back exactly 127 or 128 for a
      // half-alpha stroke, and pinning one of them would be pinning sharp's rounding. The
      // `undefined` arm is `noUncheckedIndexedAccess` being narrowed explicitly rather than
      // suppressed (tsconfig.json), not a case the buffer can actually produce.
      else if (alpha !== undefined && alpha >= 110 && alpha <= 145) translucent += 1;
    }
    expect(solid).toBeGreaterThan(2000);
    expect(translucent).toBeGreaterThan(2000);
  });

  // **The box the mark is drawn in has to be the shape the mark actually is.** `emptyStateMark`
  // states a width and a height (theme/styles.ts records why a width alone does not work), which
  // makes the drawing's proportions a fact in two files — the sheet cannot read a build
  // artifact, so the tie is made here instead of in the type system. §4.1's "derive, or tie at
  // compile time", one step later.
  //
  // Asserted as a rendered height rather than as a ratio, because that is the thing that goes
  // wrong: an untrimmed or reshaped asset in the same box does not distort — `resizeMode:
  // 'contain'` letterboxes it — so the mark simply acquires a band of empty space above and
  // below and every test that looks at colour, ink or alpha stays green. The whole defect is
  // dead vertical air, which is exactly what the trim was added to remove.
  it('is drawn in a box of its own proportions, so nothing is letterboxed', async () => {
    const { width, height } = await sharp(MARK).metadata();
    const mark = makeStyles('dark').emptyStateMark as Record<string, unknown>;
    expect(typeof mark.width).toBe('number');
    expect(typeof mark.height).toBe('number');
    // Within a point: the sheet rounds to a whole number and the asset does not.
    const proportional = (mark.width as number) * (height / width);
    expect(Math.abs((mark.height as number) - proportional)).toBeLessThan(1);
  });
});

// **Ponor's tab glyphs as the browser draws them** (issue #2): the mark and the canvas's two
// sliders, `assets/images/tab-{mark,sliders}{,@2x,@3x}.png`. The native apps hold the SVGs
// themselves as vectors (`plugins/withTabGlyphs.js`); these PNGs are the browser's copy, and
// they reach the screen the way the first-run mark does — tinted, every opaque pixel repainted
// in the bar's own ink — so they carry the same claim: one colour over a transparent ground.
// The three scales must also be one drawing: the browser picks the @2x or @3x by the screen's
// pixel ratio, and a stale one left behind by a redraw would show a different glyph on a
// high-density screen only, where nothing else would notice. The tests just below hold the
// colour and the sizes; that each scale is the SAME drawing is held by the per-scale
// comparison with a fresh render of the SVG, at the end of this file.
const TAB_GLYPH_SETS = ['tab-mark', 'tab-sliders'].map((base) =>
  [`${base}.png`, `${base}@2x.png`, `${base}@3x.png`].map((file) =>
    path.join(__dirname, '..', '..', 'assets', 'images', file),
  ),
);

describe.each(TAB_GLYPH_SETS)('the tab glyph %s', (...TAB_MARK) => {
  it.each(TAB_MARK)('%s carries exactly one colour, over a transparent ground', async (file) => {
    const { data, info } = await sharp(file).raw().toBuffer({ resolveWithObject: true });
    expect(info.channels).toBe(4);
    const inks = new Set<string>();
    let visible = 0;
    for (let i = 0; i < data.length; i += info.channels) {
      if (data[i + 3] === 0) continue;
      visible += 1;
      inks.add([data[i], data[i + 1], data[i + 2]].join(','));
    }
    // Drawn at all: a few strokes across the 28 pt square at 1× is over a hundred pixels of ink.
    expect(visible).toBeGreaterThan(100);
    expect([...inks]).toEqual(['255,255,255']);
    // ...over a transparent ground: a glyph is a few strokes, so most of its square is empty.
    // An opaque ground would pass the colour check above (one ink, everywhere) and draw as a
    // filled square in the browser's bar; the shipped glyphs leave about three quarters clear.
    const pixels = info.width * info.height;
    expect(pixels - visible).toBeGreaterThan(pixels / 2);
  });

  it('is square, and its @2x and @3x are exactly twice and three times the 1×', async () => {
    const sizes = await Promise.all(TAB_MARK.map(async (file) => sharp(file).metadata()));
    const base = sizes[0];
    if (!base) throw new Error('no 1× tab mark');
    expect(base.width).toBe(base.height);
    sizes.forEach((size, index) => {
      expect(size.width).toBe(base.width * (index + 1));
      expect(size.height).toBe(base.height * (index + 1));
    });
  });
});

// **The committed PNGs are the SVGs as they render now** (review round 2). The native apps read
// the SVGs at every prebuild, and nothing runs `npm run icons:build` in CI — so an SVG redrawn
// without rebuilding would change the phone's glyph and leave the browser on the old one, every
// test above still green (right size, one colour). This renders each glyph through the very
// function the build uses and compares the alpha, which is the glyph. A tolerance stands in for
// a rasteriser that rounds an edge pixel differently on another machine; a redrawn glyph moves
// far more than that.
// eslint-disable-next-line @typescript-eslint/no-require-imports -- a CommonJS build helper
const { renderTabGlyphPng } = require('../../scripts/renderTabGlyph.cjs') as {
  renderTabGlyphPng: (svg: string, scale: number) => Promise<Buffer>;
};
// eslint-disable-next-line @typescript-eslint/no-require-imports -- the plugin is plain CommonJS
const { TAB_GLYPHS } = require('../../plugins/withTabGlyphs') as { TAB_GLYPHS: { name: string; svg: string }[] };

async function alphaOf(png: Buffer | string) {
  const { data, info } = await sharp(png).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const alpha: number[] = [];
  for (let i = 3; i < data.length; i += info.channels) alpha.push(data[i] ?? 0);
  return { alpha, width: info.width, height: info.height };
}

describe.each(TAB_GLYPHS.flatMap((entry) => [1, 2, 3].map((scale) => [entry.svg, scale] as const)))(
  'the browser PNG of %s at %dx',
  (svg, scale) => {
    it('is that SVG as it renders now', async () => {
      const root = path.join(__dirname, '..', '..');
      const base = path.basename(svg, '.svg');
      const file = path.join(root, 'assets', 'images', scale === 1 ? `${base}.png` : `${base}@${scale}x.png`);
      const committed = await alphaOf(file);
      const rendered = await alphaOf(await renderTabGlyphPng(fs.readFileSync(path.join(root, svg), 'utf8'), scale));
      expect([committed.width, committed.height]).toEqual([rendered.width, rendered.height]);
      const diffs = committed.alpha.map((a, i) => Math.abs(a - (rendered.alpha[i] ?? 0)));
      expect(Math.max(...diffs)).toBeLessThanOrEqual(48);
      expect(diffs.reduce((sum, d) => sum + d, 0) / diffs.length).toBeLessThan(1);
    });
  },
);
